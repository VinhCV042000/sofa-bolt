export const SOFA2_ADMIN_ROOT = '/sofa2/admin';

export type Sofa2AdminColumn = {
  key: string;
  label: string;
  type?: 'text' | 'status' | 'money' | 'number';
};

export type Sofa2AdminModule = {
  slug: string;
  name: string;
  description: string;
  icon: string;
  stats: { label: string; value: string; trend?: string }[];
  columns: Sofa2AdminColumn[];
  rows: Record<string, string | number>[];
  actions?: string[];
};

export type Sofa2AdminGroup = {
  slug: string;
  name: string;
  icon: string;
  modules: Sofa2AdminModule[];
};

const money = (v: number) => v;

function mod(
  slug: string,
  name: string,
  description: string,
  icon: string,
  stats: Sofa2AdminModule['stats'],
  columns: Sofa2AdminColumn[],
  rows: Record<string, string | number>[],
  actions?: string[]
): Sofa2AdminModule {
  return { slug, name, description, icon, stats, columns, rows, actions };
}

