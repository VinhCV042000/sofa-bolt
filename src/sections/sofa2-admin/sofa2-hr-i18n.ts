const DICTS: Record<Sofa2HrLang, Dict> = { en, vi, fr, cn, ar };

// ----------------------------------------------------------------------

export function useSofa2HrT() {
  const { currentLang } = useTranslate();
  const lang = (DICTS[currentLang.value as Sofa2HrLang] ? currentLang.value : 'vi') as Sofa2HrLang;
  const dict = DICTS[lang];

  const t = (key: string, vars?: Record<string, string | number>) => {
    let text = EXTRA_UI[lang][key] ?? dict[key] ?? EXTRA_UI.vi[key] ?? vi[key] ?? key;
    if (vars) {
      Object.entries(vars).forEach(([k, v]) => {
        text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
      });
    }
    return text;
  };

  const translateValue = (value: unknown) => {
    const text = String(value ?? '');
    const key = STATUS_TRANSLATION_KEYS[text] ?? OPTION_TRANSLATION_KEYS[text];
    return key ? t(key) : text;
  };

  const translateFieldLabel = (fieldKey: string, moduleSlug: string, fallback: string) => {
    const key =
      moduleSlug === 'submit-cv' && fieldKey === 'note'
        ? 'screeningNote'
        : FIELD_TRANSLATION_KEYS[fieldKey] ?? fieldKey;
    const translated = t(key);
    return translated === key ? fallback : translated;
  };

  const translateHelper = (helper: string | undefined) => {
    if (!helper) return helper;
    const helperKeys: Record<string, string> = {
      'Được tạo tự động nếu để trống.': 'helperAutoId',
      'Mã liên kết giữa tin tuyển dụng và trang chi tiết.': 'helperJobLink',
      'Được tạo tự động khi nộp từ website.': 'helperApplicationId',
      'Google Drive, Dropbox hoặc portfolio online.': 'helperCvLink',
      'Thang 1–10.': 'helperScore',
    };
    return helperKeys[helper] ? t(helperKeys[helper]) : helper;
  };

  const translateModuleLabel = (slug: string, fallback: string) =>
    MODULE_TRANSLATION_KEYS[slug] ? t(MODULE_TRANSLATION_KEYS[slug]) : fallback;

  const translateModuleDescription = (slug: string, fallback: string) =>
    DESCRIPTION_TRANSLATION_KEYS[slug] ? t(DESCRIPTION_TRANSLATION_KEYS[slug]) : fallback;

  return {
    t,
    lang,
    translateValue,
    translateFieldLabel,
    translateHelper,
    translateModuleLabel,
    translateModuleDescription,
    translateGroupLabel: (slug: string, fallback: string) =>
      slug === 'hr' ? t('groupRecruitment') : fallback,
  };
}
